import { chromium } from 'playwright';
import path from 'node:path';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const root=path.resolve('docs/diagrams/v2-roadmap');
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto(pathToFileURL(path.join(root,'index.html')).href);
await page.evaluate(()=>document.fonts.ready);
const result=await page.evaluate(()=>({diagrams:document.querySelectorAll('svg').length,font:getComputedStyle(document.querySelector('h1')).fontFamily,overflow:document.documentElement.scrollWidth>innerWidth,clipped:[...document.querySelectorAll('svg text')].filter(text=>{const box=text.getBBox();return box.x<0||box.x+box.width>1280||box.y<0||box.y+box.height>420}).map(text=>text.textContent)}));
await page.screenshot({path:path.join(root,'overview.png')});
await page.locator('#page-3').screenshot({path:path.join(root,'customer-flow.png')});
for(let index=1;index<=18;index++) await page.locator(`#page-${index}`).screenshot({path:path.join(root,`${String(index).padStart(2,'0')}.png`)});
await page.setViewportSize({width:375,height:812});
result.mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
fs.writeFileSync(path.join(root,'browser-check.json'),JSON.stringify(result,null,2));
await browser.close();
console.log(JSON.stringify(result));
if(result.diagrams!==18||result.overflow||result.mobileOverflow||result.clipped.length) process.exitCode=1;
